import {build} from 'esbuild';
import {mkdir,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
const release=process.argv.includes('--release');
const outIndex=process.argv.indexOf('--outdir');
const outdir=outIndex<0?'lib':process.argv[outIndex+1];
if(!outdir)throw new Error('--outdir requires a path');
await mkdir(outdir,{recursive:true});
await build({entryPoints:['src/index.mjs'],outfile:join(outdir,'index.js'),bundle:true,platform:'node',format:'esm',target:'node22',external:['ws','sharp','ajv','@deepseek-ai/dsh-skill-filesystem','@deepseek-ai/schemastery'],sourcemap:!release,minify:release});
await build({entryPoints:['src/remote.mjs'],outfile:join(outdir,'remote.js'),bundle:true,platform:'browser',format:'esm',target:'es2022',minify:release});
const client=await build({entryPoints:['src/client.mjs'],bundle:true,platform:'browser',format:'cjs',target:'es2022',external:['react'],write:false,minify:release});
await writeFile(join(outdir,'client.js'),`window.__ModuleLoader__.load({id:'dsh-unreal-bridge',factory:(require)=>{const module={exports:{}};const exports=module.exports;\n${client.outputFiles[0].text}\nreturn module.exports;}});\n`);
console.log('Built DSH host, conversation dock and Remote descriptors.');
